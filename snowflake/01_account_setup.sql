--Create 3 roles
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS LOADER;
CREATE ROLE IF NOT EXISTS TRANSFORMER;
CREATE ROLE IF NOT EXISTS REPORTER;
GRANT ROLE LOADER, TRANSFORMER, REPORTER TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS LOADER_WH WITH 
WAREHOUSE_SIZE ='XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE 
initially_suspended = TRUE

CREATE WAREHOUSE IF NOT EXISTS TRANSFORMER_WH WITH
WAREHOUSE_SIZE ='XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE

CREATE WAREHOUSE IF NOT EXISTS REPORTER_WH WITH
WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE

GRANT USAGE ON WAREHOUSE LOADER_WH TO ROLE LOADER
GRANT USAGE ON WAREHOUSE TRANSFORMER_WH TO ROLE TRANSFORMER
GRANT USAGE ON WAREHOUSE REPORTER_WH TO ROLE REPORTER


--Create 2 databases - one for raw data and one for analytics (transformed data
CREATE DATABASE IF NOT EXISTS GUEST_RAW;
CREATE DATABASE IF NOT EXISTS GUEST_ANALYTICS;

GRANT OWNERSHIP ON DATABASE GUEST_RAW TO ROLE LOADER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE GUEST_ANALYTICS TO ROLE TRANSFORMER COPY CURRENT GRANTS;


--Let dbt read raw data now and in the future
GRANT USAGE ON DATABASE GUEST_RAW TO ROLE TRANSFORMER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE GUEST_RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN DATABASE GUEST_RAW TO ROLE TRANSFORMER;

GRANT USAGE ON DATABASE GUEST_ANALYTICS TO ROLE REPORTER;

--set up a spending limit
USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR IF NOT EXISTS GUEST_MONTHLY
  WITH CREDIT_QUOTA = 20
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;

ALTER WAREHOUSE LOADER_WH   SET RESOURCE_MONITOR = GUEST_MONTHLY;
ALTER WAREHOUSE TRANSFORMER_WH SET RESOURCE_MONITOR = GUEST_MONTHLY;
ALTER WAREHOUSE REPORTER_WH SET RESOURCE_MONITOR = GUEST_MONTHLY;


--give roles to myself
USE ROLE SECURITYADMIN;
GRANT ROLE LOADER TO USER AKR;
GRANT ROLE TRANSFORMER TO USER AKR;
GRANT ROLE REPORTER TO USER AKR;